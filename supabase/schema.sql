-- Run this in the Supabase SQL editor before starting the API.
create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 120),
  email text not null,
  phone text,
  message text not null check (char_length(message) between 10 and 5000),
  created_at timestamptz not null default now()
);

alter table public.contact_messages enable row level security;
-- The FastAPI server uses a private service-role key; no browser policy is required.
-- Do not add a public INSERT policy: it would enable spam through the Data API.
